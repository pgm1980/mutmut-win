"""Regression tests for Bug #4 — typing.cast() first-argument mutations skipped.

`typing.cast(type, obj)` returns ``obj`` unchanged at runtime — the first argument is a
pure type annotation. Mutations of that first argument are therefore
observable-equivalent (unkillable). They must not be generated by the mutator at all.

See critique-model-service ``_misc/mutmut-win-bugs.md`` Bug #4 for the original repro.
"""

from __future__ import annotations

from mutmut_win.mutation import create_mutations, mutate_file_contents


def _mutant_codes_for(source: str) -> list[str]:
    """Return the textual code of every mutated node (debug-friendly)."""
    _module, mutations = create_mutations(source)
    return [
        mutation.mutated_node.code
        if hasattr(mutation.mutated_node, "code")
        else type(mutation.mutated_node).__name__
        for mutation in mutations
    ]


def test_cast_unqualified_first_arg_string_is_skipped() -> None:
    """An imported ``typing.cast`` is resolved, not guessed from its spelling."""
    source = """\
from typing import cast


def normalise(obj):
    return cast("Any", obj)
"""
    mutated_code, _mutant_names = mutate_file_contents("m.py", source)

    # No mutant may rewrite the cast's first argument
    for forbidden in ("cast(None,", 'cast("XXAnyXX",', 'cast("any",', 'cast("ANY",'):
        assert forbidden not in mutated_code, (
            f"Mutant containing {forbidden!r} found — cast() first-arg mutations "
            f"must be skipped (Bug #4). Mutated code:\n{mutated_code}"
        )


def test_cast_qualified_first_arg_string_is_skipped() -> None:
    """``typing.cast("Any", obj)`` (qualified) must also be skipped."""
    source = """\
import typing


def normalise(obj):
    return typing.cast("Any", obj)
"""
    mutated_code, _ = mutate_file_contents("m.py", source)

    for forbidden in (
        "typing.cast(None,",
        'typing.cast("XXAnyXX",',
        'typing.cast("any",',
        'typing.cast("ANY",',
    ):
        assert forbidden not in mutated_code, (
            f"Mutant containing {forbidden!r} found — typing.cast() first-arg "
            f"mutations must be skipped. Mutated code:\n{mutated_code}"
        )


def test_cast_first_arg_name_is_skipped() -> None:
    """``cast(Any, obj)`` (Name first-arg) must also be skipped."""
    source = """\
from typing import Any, cast


def normalise(obj):
    return cast(Any, obj)
"""
    mutated_code, _ = mutate_file_contents("m.py", source)

    # arg_removal would turn the Name into None — also forbidden
    assert "cast(None," not in mutated_code, (
        "cast(None, obj) found — Name first-arg mutations must be skipped (Bug #4). "
        f"Mutated code:\n{mutated_code}"
    )


def test_cast_second_arg_is_still_mutable() -> None:
    """The second argument of ``cast()`` (the real value) MUST stay mutable."""
    source = """\
from typing import cast


def normalise(obj):
    return cast("Any", obj.value)
"""
    mutated_code, _mutant_names = mutate_file_contents("m.py", source)

    # arg_removal turns the second arg to None — this MUST happen, since the second
    # arg is the real runtime value.
    assert "cast('Any', None)" in mutated_code or 'cast("Any", None)' in mutated_code, (
        "cast(...) second-arg mutation should still happen — only the first arg is "
        f"a type annotation. Mutated code:\n{mutated_code}"
    )


def test_non_cast_call_first_arg_string_is_still_mutated() -> None:
    """A non-cast call with a string first arg MUST still be mutated."""
    source = """\
def f(obj):
    return some_func("Any", obj)
"""
    mutated_code, _mutant_names = mutate_file_contents("m.py", source)

    # We expect some_func("XXAnyXX", obj) to appear as one of the mutants
    assert 'some_func("XXAnyXX",' in mutated_code, (
        "Generic call with string first-arg should still be mutated — only "
        f"cast() is special-cased. Mutated code:\n{mutated_code}"
    )


def test_aliased_typing_cast_first_arg_is_skipped() -> None:
    source = """\
from typing import cast as type_cast


def normalise(obj):
    return type_cast("Any", obj)
"""
    mutated_code, _ = mutate_file_contents("m.py", source)

    assert 'type_cast("XXAnyXX",' not in mutated_code
    assert "type_cast(None," not in mutated_code


def test_local_function_named_cast_keeps_first_argument_mutable() -> None:
    source = """\
def cast(kind, value):
    return kind, value


def use_local_cast():
    return cast(1, 2)
"""
    mutated_code, names = mutate_file_contents("m.py", source)

    assert names
    assert "return cast(2, 2)" in mutated_code


def test_locally_shadowed_typing_object_is_not_treated_as_typing_module() -> None:
    source = """\
class LocalTyping:
    def cast(self, kind, value):
        return kind, value


typing = LocalTyping()


def use_local_typing():
    return typing.cast(1, 2)
"""
    mutated_code, names = mutate_file_contents("m.py", source)

    assert names
    assert "return typing.cast(2, 2)" in mutated_code
