"""S3 generation regressions against actual engine and persisted legacy data."""

from pathlib import Path

import pytest
from pydantic import BaseModel

from mutmut_win.exceptions import MutationError
from mutmut_win.file_setup import create_mutants_for_file
from mutmut_win.mutation import mutate_file_contents


class LegacyGeneration(BaseModel):
    """Actual reduced output captured from the unchanged S3 baseline."""

    source: str
    generated: str
    metadata: str
    baseline_commit: str
    import_binding: str


@pytest.fixture
def legacy_generation() -> LegacyGeneration:
    """Read the exact source, generated bytes and sidecar from baseline generation."""
    path = Path(__file__).parents[1] / "fixtures" / "s3_005_legacy_generation.json"
    return LegacyGeneration.model_validate_json(path.read_bytes())


def test_namespace_collision_blocks_partial_generation(legacy_generation: LegacyGeneration) -> None:
    """A global trampoline collision must not silently remove a tested function."""
    with pytest.raises(MutationError, match="trampoline namespace"):
        mutate_file_contents("module.py", legacy_generation.source)


def test_old_reduced_sidecar_cannot_bypass_collision_guard(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    legacy_generation: LegacyGeneration,
) -> None:
    """Historical source/hash-valid staging cannot retain its incomplete population."""
    monkeypatch.chdir(tmp_path)
    source = Path("module.py")
    source.write_bytes(legacy_generation.source.encode())
    output = Path("mutants/module.py")
    output.parent.mkdir()
    output.write_bytes(legacy_generation.generated.encode())
    sidecar = output.with_suffix(".py.meta")
    sidecar.write_bytes(legacy_generation.metadata.encode())
    before = (source.read_bytes(), output.read_bytes(), sidecar.read_bytes())
    with pytest.raises(MutationError, match="trampoline namespace"):
        create_mutants_for_file(source, output)
    assert (source.read_bytes(), output.read_bytes(), sidecar.read_bytes()) == before


def test_healthy_names_keep_both_function_populations(legacy_generation: LegacyGeneration) -> None:
    """A nearby ordinary global retains both independently named mutant families."""
    source = legacy_generation.source.replace("x_value__mutmut_shadow", "ordinary_value")
    generated, names = mutate_file_contents("module.py", source)
    compile(generated, "<healthy-generated>", "exec")
    assert any(name.startswith("x_value__mutmut_") for name in names)
    assert any(name.startswith("x_other__mutmut_") for name in names)
